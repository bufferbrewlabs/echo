import AppKit

/// Polls a pasteboard (the general one by default) for changes and records new content
/// into the history store.
final class ClipboardMonitor {
    /// Markers from the nspasteboard.org convention. Password managers and other apps
    /// set them on secrets and throwaway data that clipboard tools must not save.
    static let ignoredTypes: Set<NSPasteboard.PasteboardType> = [
        .init("org.nspasteboard.ConcealedType"),
        .init("org.nspasteboard.TransientType"),
        .init("org.nspasteboard.AutoGeneratedType")
    ]

    private let store: HistoryStore
    private let pasteboard: NSPasteboard
    private var timer: Timer?
    private var lastChangeCount: Int

    /// Set right before we programmatically write to the pasteboard (e.g. quick-paste)
    /// so the next detected change is treated as a re-use rather than a brand new item.
    var pendingProgrammaticItem: ClipboardItem?

    init(store: HistoryStore, pasteboard: NSPasteboard = .general) {
        self.store = store
        self.pasteboard = pasteboard
        self.lastChangeCount = pasteboard.changeCount
    }

    func start() {
        stop()
        let timer = Timer(timeInterval: 0.5, repeats: true) { [weak self] _ in
            self?.poll()
        }
        // .common keeps recording while a menu or a resize is tracking events.
        RunLoop.main.add(timer, forMode: .common)
        self.timer = timer
    }

    func stop() {
        timer?.invalidate()
        timer = nil
    }

    /// True when the pasteboard is marked as holding a secret or transient data.
    static func shouldIgnore(types: [NSPasteboard.PasteboardType]?) -> Bool {
        types?.contains(where: ignoredTypes.contains) ?? false
    }

    func poll() {
        guard pasteboard.changeCount != lastChangeCount else { return }
        lastChangeCount = pasteboard.changeCount

        if let pending = pendingProgrammaticItem {
            pendingProgrammaticItem = nil
            store.touch(pending)
            return
        }

        guard !Self.shouldIgnore(types: pasteboard.types) else { return }

        if let image = readImage(from: pasteboard) {
            store.addImage(image)
        } else if let text = pasteboard.string(forType: .string), !text.isEmpty {
            store.addText(text)
        }
    }

    private func readImage(from pasteboard: NSPasteboard) -> NSImage? {
        // Only real image data counts. Finder file copies carry a file URL, not .tiff/.png.
        guard let data = pasteboard.data(forType: .tiff) ?? pasteboard.data(forType: .png) else { return nil }
        return NSImage(data: data)
    }
}
